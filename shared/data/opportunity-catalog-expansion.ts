type ResearchRoute = Omit<
  Opportunity,
  | 'id'
  | 'sourceId'
  | 'externalId'
  | 'published'
  | 'verifiedAt'
  | 'priority'
  | 'searchVersion'
  | 'deadline'
  | 'eventDate'
  | 'timezone'
> & { slug: string; sources: string[] }

function researchRoute(route: ResearchRoute): Opportunity {
  const { sources, ...item } = route
  return {
    ...item,
    id: `catalog:${route.slug}`,
    sourceId: `catalog-${route.slug}`,
    externalId: route.edition || 'current',
    published: true,
    verifiedAt: observedAt,
    priority: 90,
    searchVersion: 2,
    deadline: null,
    eventDate: null,
    timezone: null,
    fieldEvidence: [
      ...(route.fieldEvidence || []),
      ...sources.map((url) => ({
        field: 'officialSource',
        url,
        observedAt,
        confirmedAt: observedAt,
      })),
    ],
  }
}

